
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.resolve(__dirname, "../src/data");

const collections = {
  students: ["students.json", "STU"],
  requests: ["requests.json", "REQ"],
  appointments: ["appointments.json", "APT"],
  goodMoralRequests: ["goodMoralRequests.json", "GMR"],
  documents: ["documents.json", "DOC"],
  counselingRecords: ["counselingRecords.json", "CR"],
  referrals: ["referrals.json", "REF"],
  followUps: ["followUps.json", "FUP"],
  programs: ["programs.json", "PRG"],
  announcements: ["announcements.json", "ANN"],
  notifications: ["notifications.json", "NOT"],
  auditLog: ["auditLog.json", "AUD"],
  walkIns: ["walkIns.json", "WLK"],
  careerServices: ["careerServices.json", "CAR"],
  recommendations: ["recommendations.json", "REC"],
  analyticsSnapshots: ["analyticsSnapshots.json", "SNAP"],
};

const pad = (number) => String(number).padStart(4, "0");

function readRecords(filename) {
  const filePath = path.join(DATA_DIR, filename);

  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing required file: ${filename}`);
  }

  const parsed = JSON.parse(fs.readFileSync(filePath, "utf8"));

  if (!Array.isArray(parsed)) {
    throw new Error(
      `${filename} is not an array. Fix its format in Stage 19.1 first.`
    );
  }

  return parsed;
}

function writeRecords(filename, records) {
  fs.writeFileSync(
    path.join(DATA_DIR, filename),
    JSON.stringify(records, null, 2) + "\n",
    "utf8"
  );
}

if (!fs.existsSync(DATA_DIR)) {
  throw new Error(`Data directory not found: ${DATA_DIR}`);
}

// Load every configured collection.
const data = {};

for (const [key, [filename]] of Object.entries(collections)) {
  data[key] = readRecords(filename);
}

// Check source IDs before changing anything.
// Duplicate old IDs make references ambiguous, so stop instead of guessing.
for (const [key, [filename]] of Object.entries(collections)) {
  const seen = new Set();

  for (const record of data[key]) {
    if (!record.id) {
      throw new Error(`${filename} contains a record without an id.`);
    }

    if (seen.has(record.id)) {
      throw new Error(
        `${filename} contains duplicate original ID "${record.id}". Fix duplicates first.`
      );
    }

    seen.add(record.id);
  }
}

// Build maps from old IDs to canonical IDs.
const idMaps = {};

for (const [key, [, prefix]] of Object.entries(collections)) {
  idMaps[key] = new Map();

  data[key].forEach((record, index) => {
    idMaps[key].set(record.id, `${prefix}-${pad(index + 1)}`);
  });
}

// Preserve the relationship between existing users and students.
// This also helps when student IDs were already regenerated by Stage 19.2.
const originalStudents = data.students.map((student) => ({ ...student }));
const originalUsersPath = path.join(DATA_DIR, "users.json");

if (!fs.existsSync(originalUsersPath)) {
  throw new Error("Missing required file: users.json");
}

const users = JSON.parse(fs.readFileSync(originalUsersPath, "utf8"));

if (!Array.isArray(users)) {
  throw new Error("users.json is not an array.");
}

const studentIdByEmail = new Map(
  originalStudents
    .filter((student) => student.email)
    .map((student) => [student.email.toLowerCase(), student.id])
);

const studentIdByName = new Map(
  originalStudents
    .filter((student) => student.name)
    .map((student) => [student.name.trim().toLowerCase(), student.id])
);

// Normalize primary IDs.
for (const [key, [filename]] of Object.entries(collections)) {
  data[key] = data[key].map((record) => ({
    ...record,
    id: idMaps[key].get(record.id),
  }));

  writeRecords(filename, data[key]);
}

// Update foreign keys in all collections.
const studentMap = idMaps.students;
const appointmentMap = idMaps.appointments;
const documentMap = idMaps.documents;
const counselingMap = idMaps.counselingRecords;

function updateReference(record, field, map) {
  if (record[field] && map.has(record[field])) {
    record[field] = map.get(record[field]);
  }
}

for (const [key, [filename]] of Object.entries(collections)) {
  data[key] = data[key].map((record) => {
    const updated = { ...record };

    updateReference(updated, "studentId", studentMap);
    updateReference(updated, "appointmentId", appointmentMap);
    updateReference(updated, "documentId", documentMap);
    updateReference(updated, "counselingRecordId", counselingMap);

    return updated;
  });

  writeRecords(filename, data[key]);
}

// Update users separately because users.json has its own IDs and roles.
const userIds = new Set();

users.forEach((user) => {
  if (!user.id) {
    throw new Error("users.json contains a record without an id.");
  }

  if (userIds.has(user.id)) {
    throw new Error(`users.json contains duplicate ID "${user.id}".`);
  }

  userIds.add(user.id);

  if (user.studentId) {
    let matchedStudentId = user.studentId;

    // First use the original ID mapping.
    if (studentMap.has(matchedStudentId)) {
      matchedStudentId = studentMap.get(matchedStudentId);
    } else {
      // If IDs changed earlier, try email or name.
      const matchedStudent =
        originalStudents.find(
          (student) =>
            student.email &&
            user.email &&
            student.email.toLowerCase() === user.email.toLowerCase()
        ) ||
        originalStudents.find(
          (student) =>
            student.name &&
            user.name &&
            student.name.trim().toLowerCase() ===
              user.name.trim().toLowerCase()
        );

      if (matchedStudent && studentMap.has(matchedStudent.id)) {
        matchedStudentId = studentMap.get(matchedStudent.id);
      }
    }

    user.studentId = matchedStudentId;
  }
});

fs.writeFileSync(
  originalUsersPath,
  JSON.stringify(users, null, 2) + "\n",
  "utf8"
);

console.log("Primary IDs standardized.");
console.log("Foreign-key references updated where a matching ID was found.");
console.log("Next, run: node scripts/validateReferences.mjs");
